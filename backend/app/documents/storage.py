from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from uuid import UUID

from app.documents.database import DATA_DIRECTORY

UPLOAD_DIRECTORY = DATA_DIRECTORY / "uploads"

_EXTENSIONS_BY_CONTENT_TYPE = {
  "application/pdf": ".pdf",
  "image/png": ".png",
  "image/jpeg": ".jpg",
}
_CONTROLLED_EXTENSIONS = tuple(_EXTENSIONS_BY_CONTENT_TYPE.values())


class AmbiguousDocumentDeletionError(Exception):
  """More than one controlled tombstone exists for one generated ID."""


@dataclass(frozen=True, slots=True)
class StagedDocumentDeletion:
  """One exact source path and its controlled same-directory tombstone."""

  original_path: Path
  tombstone_path: Path | None


def initialize_storage() -> None:
  """Create the upload directory if it does not exist yet."""
  UPLOAD_DIRECTORY.mkdir(parents=True, exist_ok=True)


def document_path(document_id: str, content_type: str) -> Path:
  """Build one stored path from the generated id and the sniffed type."""
  extension = _EXTENSIONS_BY_CONTENT_TYPE.get(content_type, "")
  return UPLOAD_DIRECTORY / f"{document_id}{extension}"


def save_document(document_id: str, document_bytes: bytes, content_type: str) -> Path:
  """Store the original bytes under a generated name, never a client name."""
  initialize_storage()
  path = document_path(document_id, content_type)
  path.write_bytes(document_bytes)
  return path


def stage_document_deletion(
  document_id: str,
  content_type: str,
) -> StagedDocumentDeletion:
  """Move one exact source to a retryable tombstone before deleting its row."""
  canonical_id = _canonical_generated_document_id(document_id)
  extension = _EXTENSIONS_BY_CONTENT_TYPE.get(content_type)
  if canonical_id is None or extension is None:
    raise ValueError("Stored document deletion metadata is invalid.")
  original = UPLOAD_DIRECTORY / f"{canonical_id}{extension}"
  tombstone = original.with_name(f".{original.name}.deleting")
  if original.exists():
    if tombstone.exists():
      raise FileExistsError("A deletion tombstone already exists for this document.")
    original.rename(tombstone)
    return StagedDocumentDeletion(original, tombstone)
  if tombstone.exists():
    return StagedDocumentDeletion(original, tombstone)
  return StagedDocumentDeletion(original, None)


def pending_document_deletion(
  document_id: str,
) -> StagedDocumentDeletion | None:
  """Find one rowless tombstone using only a canonical generated UUID."""
  canonical_id = _canonical_generated_document_id(document_id)
  if canonical_id is None:
    return None

  candidates = tuple(
    StagedDocumentDeletion(
      original_path=UPLOAD_DIRECTORY / f"{canonical_id}{extension}",
      tombstone_path=(
        UPLOAD_DIRECTORY / f".{canonical_id}{extension}.deleting"
      ),
    )
    for extension in _CONTROLLED_EXTENSIONS
  )
  existing = tuple(
    candidate
    for candidate in candidates
    if candidate.tombstone_path is not None
    and candidate.tombstone_path.exists()
  )
  if len(existing) > 1:
    raise AmbiguousDocumentDeletionError(
      "Multiple deletion tombstones exist for this document identifier."
    )
  return existing[0] if existing else None


def restore_document_deletion(staged: StagedDocumentDeletion) -> None:
  """Move a staged source back without overwriting another exact source."""
  tombstone = staged.tombstone_path
  if tombstone is None or not tombstone.exists():
    return
  if staged.original_path.exists():
    raise FileExistsError("Cannot restore a deletion over an existing source file.")
  tombstone.rename(staged.original_path)


def finish_document_deletion(staged: StagedDocumentDeletion) -> None:
  """Remove the one controlled tombstone after its row deletion commits."""
  if staged.tombstone_path is not None:
    staged.tombstone_path.unlink(missing_ok=True)


def _canonical_generated_document_id(document_id: str) -> str | None:
  """Accept only the lowercase hyphenated UUIDv4 format generated by the app."""
  try:
    parsed = UUID(document_id)
  except (AttributeError, TypeError, ValueError):
    return None
  canonical = str(parsed)
  if parsed.version != 4 or document_id != canonical:
    return None
  return canonical
